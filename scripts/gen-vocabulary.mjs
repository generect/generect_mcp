// Regenerates src/vocabulary.generated.ts from the backend's own filter data.
//
// Why generated and not hand-written: three of these vocabularies are enforced
// by the API (an unknown value is a 400) and two are NOT (an unknown value
// silently matches nothing — see the header of vocabulary.ts). Typing 434
// industry names by hand is how a "close enough" list ends up shipping and
// quietly zeroing customers' searches.
//
// Usage:  node scripts/gen-vocabulary.mjs [path-to-api_parser-checkout]
// Default checkout path is the read-only mount used on the ops box.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const repo = process.argv[2] || '/home/andrii/generect/repos/api_parser';

const INDUSTRY_JSON = join(repo, 'linkedin_parser/utils/categories_relationship.json');
const DATA_DICTS = join(repo, 'linkedin_parser/utils/urlcreator/data_dicts.py');
const LEAD_LIST_URL = join(repo, 'linkedin/utils/lead_list_url.py');

/**
 * Pull a `NAME = { "k": "v", ... }` python dict out of a source file.
 *
 * Brace-balanced rather than regex-terminated: several of these dicts are
 * written on a single line, and a `\n}` anchor happily swallows the two dicts
 * that follow (that bug silently turned 5 follower ranges into 19).
 */
function pyDict(source, name) {
  const start = source.search(new RegExp(`(^|\\n)\\s*${name}\\s*=\\s*\\{`));
  if (start === -1) throw new Error(`could not find python dict ${name}`);
  const open = source.indexOf('{', start);
  let depth = 0;
  let end = -1;
  for (let i = open; i < source.length; i += 1) {
    if (source[i] === '{') depth += 1;
    else if (source[i] === '}') {
      depth -= 1;
      if (depth === 0) {
        end = i;
        break;
      }
    }
  }
  if (end === -1) throw new Error(`unterminated python dict ${name}`);
  const body = source.slice(open + 1, end);
  const out = {};
  for (const [, k, v] of body.matchAll(/["']([^"']+)["']\s*:\s*["']([^"']*)["']/g)) out[k] = v;
  if (Object.keys(out).length === 0) throw new Error(`${name} parsed empty`);
  return out;
}

const industries = JSON.parse(readFileSync(INDUSTRY_JSON, 'utf8'));
const dicts = readFileSync(DATA_DICTS, 'utf8');
const leadListUrl = readFileSync(LEAD_LIST_URL, 'utf8');

// Industry tree: name plus parent name, so the server can explain that a broad
// pick already covers the narrow one the caller also passed.
const byId = new Map(Object.entries(industries).map(([id, v]) => [id, v]));
const industryRows = [...byId.values()]
  .map(v => ({ name: v.name, parent: v.parent ? byId.get(String(v.parent))?.name ?? null : null }))
  .sort((a, b) => a.name.localeCompare(b.name));

const seniorities = Object.values(pyDict(dicts, 'SENIORITY_LEVEL'));
const functions = Object.values(pyDict(dicts, 'LEAD_FUNCTIONS')).sort();
const followerRanges = Object.values(pyDict(dicts, 'NUM_OF_FOLLOWERS'));
// company_types: the v1 API validates against lead_list_url.type_dict, NOT the
// Sales-Navigator COMPANY_TYPE dict in data_dicts.py — those two disagree
// ("Educational" vs "Educational Institution") and only the former is accepted.
const companyTypes = Object.values(pyDict(leadListUrl, 'type_dict')).sort();

// Headcount buckets: the API itself lists the valid values in its 400 message.
const headcounts = ['1-10', '11-50', '51-200', '201-500', '501-1000', '1001-5000', '5001-10000', '10 000+'];

const banner = `// GENERATED by scripts/gen-vocabulary.mjs — do not edit by hand.
// Source of truth: generect/api_parser
//   linkedin_parser/utils/categories_relationship.json   (industries)
//   linkedin_parser/utils/urlcreator/data_dicts.py       (seniorities, functions, follower ranges)
//   linkedin/utils/lead_list_url.py  -> type_dict        (company types)
// Regenerate with: node scripts/gen-vocabulary.mjs <api_parser checkout>
`;

const body = `${banner}
export interface IndustryNode {
  name: string;
  parent: string | null;
}

export const INDUSTRIES: readonly IndustryNode[] = ${JSON.stringify(industryRows, null, 2)} as const;

export const SENIORITIES: readonly string[] = ${JSON.stringify(seniorities, null, 2)} as const;

export const FUNCTIONS: readonly string[] = ${JSON.stringify(functions, null, 2)} as const;

export const COMPANY_TYPES: readonly string[] = ${JSON.stringify(companyTypes, null, 2)} as const;

export const HEADCOUNTS: readonly string[] = ${JSON.stringify(headcounts, null, 2)} as const;

export const FOLLOWER_RANGES: readonly string[] = ${JSON.stringify(followerRanges, null, 2)} as const;
`;

const target = new URL('../src/vocabulary.generated.ts', import.meta.url);
writeFileSync(target, body);
console.log(
  `wrote ${target.pathname}: ${industryRows.length} industries, ${seniorities.length} seniorities, ` +
    `${functions.length} functions, ${companyTypes.length} company types, ${followerRanges.length} follower ranges`,
);
